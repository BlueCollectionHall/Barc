-- 订正「新年」节日的统一索引（V10 种子数据的索引算错了）
--
-- 背景：统一索引的算法是「月份 * 32 + 日」（见 MonthDayRangeUtils.toIndex），
-- 而 V10 的种子数据按「月份 * 31 + 日」手算，写成了 start_index = 386、end_index = 478。
-- 其中 478 已越出合法索引上界 415（12-31），导致这一行被当成「非跨年」区间：
--   1、用户端在新年季（12 月与次年 1、2 月）判定不到新年，绑定新年的背景图不会展示；
--   2、区间重叠校验出现漏洞，可能造出真正重叠的节日数据。
--
-- 正确值：12-01 → 385，02-29 → 93，此时 start_index > end_index，正确表达「跨年环绕」。
-- 结束日同时订正为 02-29（原 V10 写成 02-28）：管理端把「月份式」的边界定义为该月最后一天
-- （2 月按闰年上限 29 天），只有 end_month/end_day 与 end_index 一致时，
-- 「新年」才会在管理端被正确回显为月份式而不是日期式，也才能覆盖闰年的 2 月 29 日。
-- 注意：V10 已在数据库上执行过，不能就地修改（会破坏 Flyway checksum 校验），因此用 V11 订正。
UPDATE festival
SET end_day = 29, start_index = 385, end_index = 93, updated_at = CURRENT_TIMESTAMP
WHERE id = '0000000000000000000000000000f001';
